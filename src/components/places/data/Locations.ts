import {
  Building,
  BuildingName,
  findBuildingByName,
} from "./BuildingLocations";
import Rooms, { Room } from "./RoomLocations";

interface Location {
  name: string;
  pisaName: string;
  building: Building | undefined;
  room: Room | undefined;
}

function findLocation(
  buildingName: BuildingName,
  roomName?: string,
): Pick<Location, "building" | "room"> {
  const building = findBuildingByName(buildingName);
  const room = roomName
    ? Rooms.find((room) => room.building === building && room.name === roomName)
    : undefined;
  return { building, room };
}

function createLocation(
  name: string,
  pisaName: string,
  buildingName: BuildingName,
  roomName?: string,
): Location {
  return {
    name,
    pisaName,
    ...findLocation(buildingName, roomName),
  };
}

